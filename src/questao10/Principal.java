package questao10;
// 10. Escrever um programa para exibir os números de 1 até 50 na tela usando o **do..while**.


public class Principal {

    public static void main(String[] args) {

        int i=1;

        do{

            System.out.printf("%d\n", i);
            i++;

        }while(i <= 50);
        
    }
    
}
