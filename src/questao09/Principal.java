package questao09;
// 9. Escrever um programa para exibir os números de 1 até 50 na tela usando o **while**.


public class Principal {

    public static void main(String[] args) {

        int i=1;
        
        while(i <= 50){

            System.out.printf("%d\n", i);
            i++;
        }
    }
    
}
